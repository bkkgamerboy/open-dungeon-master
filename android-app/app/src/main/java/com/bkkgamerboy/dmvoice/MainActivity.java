package com.bkkgamerboy.dmvoice;

import android.Manifest;
import android.app.Activity;
import android.content.Context;
import android.content.Intent;
import android.content.pm.PackageManager;
import android.graphics.Color;
import android.os.Build;
import android.os.Bundle;
import android.speech.tts.TextToSpeech;
import android.view.Gravity;
import android.view.inputmethod.InputMethodManager;
import android.webkit.JavascriptInterface;
import android.webkit.PermissionRequest;
import android.webkit.WebChromeClient;
import android.webkit.WebResourceRequest;
import android.webkit.WebView;
import android.webkit.WebViewClient;
import android.widget.Button;
import android.widget.EditText;
import android.widget.LinearLayout;
import android.widget.TextView;
import android.widget.Toast;
import java.util.Locale;

/**
 * Standalone APK shell around a separately running Open Dungeon Master server.
 * Spoken narration is synthesized on the Android device, never by a speech API.
 */
public class MainActivity extends Activity implements TextToSpeech.OnInitListener {
    private static final String PREF_SERVER = "game_server_url";
    private WebView web;
    private TextToSpeech speech;
    private boolean speechReady;
    private boolean voiceEnabled = true;
    private LinearLayout root;
    private Button voiceButton;
    private PermissionRequest microphoneRequest;

    @Override public void onCreate(Bundle state) {
        super.onCreate(state);
        getWindow().setStatusBarColor(Color.rgb(14, 12, 29));
        getWindow().setNavigationBarColor(Color.rgb(14, 12, 29));
        speech = new TextToSpeech(this, this);
        root = new LinearLayout(this);
        root.setOrientation(LinearLayout.VERTICAL);
        root.setBackgroundColor(Color.rgb(18, 15, 35));
        setContentView(root);
        String saved = getPreferences(MODE_PRIVATE).getString(PREF_SERVER, "");
        if (saved.isEmpty()) showSettings(""); else showGame(saved);
    }

    private int dp(int size) {
        return (int)(getResources().getDisplayMetrics().density * size + .5f);
    }

    private Button button(String name) {
        Button b = new Button(this);
        b.setText(name);
        b.setAllCaps(false);
        return b;
    }

    private TextView label(String value, int size) {
        TextView t = new TextView(this);
        t.setText(value);
        t.setTextSize(size);
        t.setTextColor(Color.WHITE);
        t.setPadding(dp(12), dp(10), dp(12), dp(10));
        return t;
    }

    private void showSettings(String initialUrl) {
        if (speech != null) speech.stop();
        if (web != null) {
            web.destroy();
            web = null;
        }
        root.removeAllViews();
        root.addView(label("Dungeon Master — Android Voice", 21));
        root.addView(label(
            "Enter the address where your existing Open Dungeon Master game is running. "
            + "This APK adds local Android speech; it does not host the game server.", 15));
        EditText edit = new EditText(this);
        edit.setSingleLine(true);
        edit.setText(initialUrl);
        edit.setHint("http://192.168.1.2:3005 or https://your-game");
        edit.setTextColor(Color.WHITE);
        edit.setHintTextColor(0xffaaaaaa);
        edit.setInputType(android.text.InputType.TYPE_CLASS_TEXT
            | android.text.InputType.TYPE_TEXT_VARIATION_URI);
        root.addView(edit);
        Button connect = button("Connect to game");
        root.addView(connect);
        connect.setOnClickListener(v -> {
            String url = edit.getText().toString().trim();
            if (!url.startsWith("http://") && !url.startsWith("https://")) {
                Toast.makeText(this, "Enter an http:// or https:// URL", Toast.LENGTH_LONG).show();
                return;
            }
            android.net.Uri parsed = android.net.Uri.parse(url);
            if (parsed.getHost() == null || parsed.getHost().isEmpty()) {
                Toast.makeText(this, "Invalid game address", Toast.LENGTH_LONG).show();
                return;
            }
            getPreferences(MODE_PRIVATE).edit().putString(PREF_SERVER, url).apply();
            ((InputMethodManager)getSystemService(Context.INPUT_METHOD_SERVICE))
                .hideSoftInputFromWindow(edit.getWindowToken(), 0);
            showGame(url);
        });
        root.addView(label("Speech is free and generated by your Android TTS engine. "
            + "Download an English voice in Android settings for reliable offline synthesis. "
            + "Use the keyboard microphone (Gboard) for dictation.", 14));
    }

    private boolean sameOrigin(String first, String second) {
        try {
            android.net.Uri a = android.net.Uri.parse(first);
            android.net.Uri b = android.net.Uri.parse(second);
            int pa = a.getPort() < 0 ? ("https".equalsIgnoreCase(a.getScheme()) ? 443 : 80) : a.getPort();
            int pb = b.getPort() < 0 ? ("https".equalsIgnoreCase(b.getScheme()) ? 443 : 80) : b.getPort();
            return a.getScheme() != null && a.getScheme().equalsIgnoreCase(b.getScheme())
                && a.getHost() != null && a.getHost().equalsIgnoreCase(b.getHost()) && pa == pb;
        } catch (Exception ex) {
            return false;
        }
    }

    private void showGame(String url) {
        root.removeAllViews();
        LinearLayout bar = new LinearLayout(this);
        bar.setGravity(Gravity.CENTER_VERTICAL);
        Button server = button("Server");
        bar.addView(server);
        server.setOnClickListener(v -> showSettings(url));
        voiceButton = button("Voice ON");
        bar.addView(voiceButton);
        voiceButton.setOnClickListener(v -> {
            voiceEnabled = !voiceEnabled;
            voiceButton.setText(voiceEnabled ? "Voice ON" : "Voice OFF");
            if (!voiceEnabled && speech != null) speech.stop();
        });
        Button stop = button("Stop");
        bar.addView(stop);
        stop.setOnClickListener(v -> { if (speech != null) speech.stop(); });
        root.addView(bar);

        web = new WebView(this);
        root.addView(web, new LinearLayout.LayoutParams(-1, 0, 1));
        web.getSettings().setJavaScriptEnabled(true);
        web.getSettings().setDomStorageEnabled(true);
        web.getSettings().setMediaPlaybackRequiresUserGesture(false);
        web.getSettings().setSupportZoom(false);
        web.addJavascriptInterface(new NarratorBridge(), "AndroidNarrator");
        web.setWebChromeClient(new WebChromeClient() {
            @Override public void onPermissionRequest(PermissionRequest request) {
                runOnUiThread(() -> {
                    if (web == null || !sameOrigin(request.getOrigin().toString(), url)) {
                        request.deny();
                        return;
                    }
                    boolean audio = false;
                    for (String resource : request.getResources()) {
                        if (PermissionRequest.RESOURCE_AUDIO_CAPTURE.equals(resource)) audio = true;
                    }
                    if (!audio) {
                        request.deny();
                        return;
                    }
                    microphoneRequest = request;
                    if (Build.VERSION.SDK_INT >= 23
                        && checkSelfPermission(Manifest.permission.RECORD_AUDIO)
                            != PackageManager.PERMISSION_GRANTED) {
                        requestPermissions(new String[]{Manifest.permission.RECORD_AUDIO}, 27);
                    } else {
                        grantMicrophone();
                    }
                });
            }
            @Override public void onPermissionRequestCanceled(PermissionRequest request) {
                if (microphoneRequest == request) microphoneRequest = null;
            }
        });
        web.setWebViewClient(new WebViewClient() {
            @Override public boolean shouldOverrideUrlLoading(WebView view, WebResourceRequest request) {
                android.net.Uri next = request.getUrl();
                if (sameOrigin(next.toString(), url)) return false;
                try {
                    startActivity(new Intent(Intent.ACTION_VIEW, next));
                } catch (Exception ex) {
                    Toast.makeText(MainActivity.this, "Cannot open external link", Toast.LENGTH_SHORT).show();
                }
                return true;
            }
            @Override public void onPageFinished(WebView view, String pageUrl) {
                if (sameOrigin(pageUrl, url)) installNarratorObserver();
            }
        });
        web.loadUrl(url);
    }

    private void grantMicrophone() {
        if (microphoneRequest == null) return;
        microphoneRequest.grant(new String[]{PermissionRequest.RESOURCE_AUDIO_CAPTURE});
        microphoneRequest = null;
    }

    @Override public void onRequestPermissionsResult(int code, String[] permissions, int[] result) {
        super.onRequestPermissionsResult(code, permissions, result);
        if (code == 27 && microphoneRequest != null) {
            if (result.length > 0 && result[0] == PackageManager.PERMISSION_GRANTED) {
                grantMicrophone();
            } else {
                microphoneRequest.deny();
                microphoneRequest = null;
            }
        }
    }

    @Override public void onInit(int status) {
        if (status != TextToSpeech.SUCCESS || speech == null) return;
        int locale = speech.setLanguage(Locale.UK);
        if (locale == TextToSpeech.LANG_MISSING_DATA
            || locale == TextToSpeech.LANG_NOT_SUPPORTED) {
            speech.setLanguage(Locale.ENGLISH);
        }
        speech.setSpeechRate(1.0f);
        speechReady = true;
    }

    private final class NarratorBridge {
        @JavascriptInterface public void speak(String text) {
            runOnUiThread(() -> {
                if (!voiceEnabled || !speechReady || speech == null || web == null) return;
                String origin = getPreferences(MODE_PRIVATE).getString(PREF_SERVER, "");
                if (!sameOrigin(web.getUrl(), origin)) return;
                String words = text.replaceAll("\\s+", " ").trim();
                if (words.isEmpty()) return;
                int chunkSize = Math.min(3000, TextToSpeech.getMaxSpeechInputLength() - 1);
                int start = 0;
                while (start < words.length()) {
                    int end = Math.min(start + chunkSize, words.length());
                    if (end < words.length()) {
                        int split = words.lastIndexOf(' ', end);
                        if (split > start + chunkSize / 2) end = split;
                    }
                    String segment = words.substring(start, end).trim();
                    if (!segment.isEmpty()) {
                        speech.speak(segment, TextToSpeech.QUEUE_ADD, null,
                            "dm_" + System.nanoTime());
                    }
                    start = end;
                }
            });
        }
    }

    private void installNarratorObserver() {
        if (web == null) return;
        // React app is unchanged: only newly inserted DM messages are read aloud.
        // Ignore existing transcript during initial startup or route changes.
        String script = "(function(){if(window.__dmAndroidObserver)return;"
            + "window.__dmAndroidObserver=true;"
            + "let seen=new WeakSet(),last=location.pathname,quiet=Date.now()+2500,pending=0;"
            + "function items(){return document.querySelectorAll('.session-dm');}"
            + "function mark(){items().forEach(x=>seen.add(x));}"
            + "function scan(){if(location.pathname!==last){last=location.pathname;quiet=Date.now()+2500;mark();}"
            + "if(Date.now()<quiet){mark();return;}"
            + "items().forEach(x=>{if(seen.has(x))return;seen.add(x);"
            + "let body=x.querySelector('.session-dm-body');if(!body)return;"
            + "let words=(body.innerText||body.textContent||'').trim();"
            + "words=words.replace(/\\[roll:[^\\]]+\\]/g,' ').trim();"
            + "if(words.length>8)AndroidNarrator.speak(words);});}"
            + "mark();new MutationObserver(()=>{clearTimeout(pending);pending=setTimeout(scan,220);})"
            + ".observe(document.documentElement,{childList:true,subtree:true});"
            + "setInterval(scan,700);"
            + "})();";
        web.evaluateJavascript(script, null);
    }

    @Override public void onBackPressed() {
        if (web != null && web.canGoBack()) {
            web.goBack();
        } else if (web != null) {
            showSettings(web.getUrl());
        } else {
            super.onBackPressed();
        }
    }

    @Override protected void onDestroy() {
        if (speech != null) {
            speech.stop();
            speech.shutdown();
            speech = null;
        }
        if (web != null) {
            web.destroy();
            web = null;
        }
        super.onDestroy();
    }
}
